/**
 * Builds public/data/reference/countries.json: one entry per country that
 * appears in BACI, keyed by ISO 3166-1 alpha-2.
 *
 *   { "CL": { "iso3": "CHL", "m49": "152", "baci": 152, "name": "Chile",
 *             "region": "Americas", "subregion": "South America",
 *             "anchor": [-71.4, -33.5] } }
 *
 * anchor = Natural Earth label point [lon, lat]: where the map puts the
 * country's marker (it lies inside the country, unlike a centroid).
 *
 * Usage: node scripts/pipeline/build-countries.js [--baci <zip>] [--ne <dbf>]
 */

import fs from 'node:fs';
import {
  BACI_ZIP, NE_DBF, BACI_SOURCE_ID, parseArgs, requireFile, readBaciCountries, readDbf
} from './lib.js';

const OUT = 'public/data/reference/countries.json';
const NE_SOURCE_ID = 'naturalearth-5.1.1';

const args = parseArgs();
const baciZip = args.baci || BACI_ZIP;
const neDbf = args.ne || NE_DBF;
requireFile(baciZip, 'Download BACI (see scripts/pipeline/lib.js).');
requireFile(neDbf, 'Download and unzip Natural Earth admin 0 countries 1:50m (see scripts/pipeline/lib.js).');

const round = (n) => Math.round(n * 1000) / 1000;
const clean = (v) => (v && v !== '-99' ? v : null);

const ne = readDbf(neDbf);
const neByIso3 = new Map();
const neByIso2 = new Map();
for (const rec of ne) {
  const iso3 = clean(rec.ISO_A3_EH);
  const iso2 = clean(rec.ISO_A2_EH);
  // Prefer the main record when several share a code (e.g. a country and its dependency)
  if (iso3 && !neByIso3.has(iso3)) neByIso3.set(iso3, rec);
  if (iso2 && !neByIso2.has(iso2)) neByIso2.set(iso2, rec);
}

const baci = await readBaciCountries(baciZip);
const countries = {};
const unmatched = [];
for (const c of [...baci.values()].sort((a, b) => a.code - b.code)) {
  if (!c.iso2) continue; // regional "nes" aggregates
  if (/\(\.\.\.\d{4}\)/.test(c.name)) continue; // codes of countries that no longer exist, e.g. "Sudan (...2011)"
  const rec = neByIso3.get(c.iso3) || neByIso2.get(c.iso2);
  if (!rec) unmatched.push(`${c.iso2} ${c.name}`);
  const m49 = rec && rec.ISO_N3_EH && rec.ISO_N3_EH !== '-99' ? String(rec.ISO_N3_EH).padStart(3, '0') : null;
  countries[c.iso2] = {
    iso3: c.iso3,
    m49,
    baci: c.code,
    name: rec?.NAME_LONG || c.name,
    region: rec?.REGION_UN || null,
    subregion: rec?.SUBREGION || null,
    anchor: rec ? [round(rec.LABEL_X), round(rec.LABEL_Y)] : null
  };
}

const sorted = Object.fromEntries(Object.entries(countries).sort(([a], [b]) => a.localeCompare(b)));
const metadata = {
  description: 'Countries and territories that appear in the trade data, keyed by ISO 3166-1 alpha-2. anchor = [lon, lat] of the label point, where the map puts the country marker; null if Natural Earth has no shape for the territory. Generated by scripts/pipeline/build-countries.js – do not edit by hand.',
  sources: [BACI_SOURCE_ID, NE_SOURCE_ID],
  generated: new Date().toISOString().slice(0, 10),
  notes: {
    TW: 'BACI reports Taiwan as "Other Asia, nes" (code 490).',
    disputed: 'Names and label points follow the Natural Earth default view; they imply no position on disputed territories.'
  }
};

// One country per line keeps diffs readable
const body = Object.entries(sorted).map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(',\n');
fs.writeFileSync(OUT, `{\n  "metadata": ${JSON.stringify(metadata, null, 2).replace(/\n/g, '\n  ')},\n  "countries": {\n${body}\n  }\n}\n`);

console.log(`[countries] ${Object.keys(sorted).length} countries → ${OUT}`);
if (unmatched.length) console.log(`[countries] no Natural Earth shape (anchor null): ${unmatched.join(', ')}`);
